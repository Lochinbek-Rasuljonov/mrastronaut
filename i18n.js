let lang = 'uz';

const STORAGE_KEY = "mrastronaut_lang";

function normalizeLang(code) {
  if (!code || typeof code !== "string") return null;
  const c = code.toLowerCase().trim();
  if (c === "uz" || c === "uz-latn" || c === "uz_uz" || c === "uz-uz") return "uz";
  if (c === "cy" || c === "uz-cyrl" || c === "uz_cyrl" || c === "ўз") return "cy";
  if (c === "ru" || c.startsWith("ru-") || c.startsWith("ru_")) return "ru";
  if (c === "en" || c.startsWith("en-") || c.startsWith("en_")) return "en";
  return null;
}

function applyLang(l) {
  const norm = normalizeLang(l) || 'uz';
  l = norm;
  lang = l;
  try {
    localStorage.setItem(STORAGE_KEY, l);
  } catch (e) {}

  const t = T[l] || T.uz;
  document.querySelectorAll('[data-key]').forEach(el => {
    const k = el.dataset.key;
    if (t[k] !== undefined) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = t[k];
      } else if (el.tagName === 'META') {
        el.setAttribute('content', t[k]);
      } else {
        el.textContent = t[k];
      }
    }
    // Handle data-suffix translations dynamically
    if (el.hasAttribute('data-suffix') && t[k + '_suffix'] !== undefined) {
      el.dataset.suffix = t[k + '_suffix'];
      // Re-apply static text in case animation already finished or hasn't started
      if (!el.tagName.match(/INPUT|TEXTAREA|META/)) {
        const target = el.dataset.target || '';
        el.textContent = target + t[k + '_suffix'];
      }
    }
  });

  // Keep dropdown value translated if an option was selected
  const selectedDd = document.querySelector('.dropdown-selected');
  const hiddenInput = document.getElementById('f-service');
  if (selectedDd && hiddenInput && selectedDd.dataset.key && selectedDd.dataset.key !== 'f_sel') {
    if (t[selectedDd.dataset.key]) {
      hiddenInput.value = t[selectedDd.dataset.key];
    }
  }

  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === l);
  });
  
  if (l === 'cy') {
    document.documentElement.lang = 'uz-Cyrl';
  } else {
    document.documentElement.lang = l;
  }

  if (t['page_title']) {
    document.title = t['page_title'];
  }
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && t['meta_desc']) {
    metaDesc.setAttribute('content', t['meta_desc']);
  }
}

function getInitialLang() {
  try {
    const params = new URLSearchParams(window.location.search);
    const urlLang = normalizeLang(params.get("lang") || params.get("locale"));
    if (urlLang) {
      return urlLang;
    }
  } catch (e) {}
  try {
    const stored = normalizeLang(localStorage.getItem(STORAGE_KEY));
    if (stored) {
      return stored;
    }
  } catch (e) {}
  return 'uz';
}

document.addEventListener('DOMContentLoaded', () => {
  applyLang(getInitialLang());
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.addEventListener('click', () => applyLang(b.dataset.lang));
  });
});
